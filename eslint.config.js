import js from "@eslint/js";
import prettierConfig from "eslint-config-prettier";
import solid from "eslint-plugin-solid/configs/typescript";
import globals from "globals";
import tseslint from "typescript-eslint";

/**
 * Flat ESLint config for the frontend, the E2E suite, and the repo scripts.
 *
 * Formatting is prettier's job, not ESLint's — `eslint-config-prettier` (last in
 * the list) switches off every rule that would fight it.
 *
 * Deliberately **not** type-aware (no `projectService`): `tsc --noEmit` already
 * covers the typed rules that need a program, and type-aware linting would have to
 * be taught about the three tsconfigs plus the out-of-project `scripts/*.ts`.
 * `recommendedTypeChecked` (chiefly `no-floating-promises`) is a planned ratchet
 * step — see `docs/code-hygiene.md`.
 */
export default tseslint.config(
  {
    ignores: [
      "node_modules/**",
      "dist/**",
      "site/**",
      ".npm-cache/**",
      "logs/**",
      "e2e/artifacts/**",
      "e2e/.fixtures/**",
      "public/fonts/**",
      // Generated by ts-rs from the Rust boundary types — never lint these.
      "src/bindings/**",
      // Cargo's build tree (like `dist/**`): compiled Rust plus generated JS glue
      // and binary assets. Without this, `eslint .` walks it and fails to parse
      // the binaries under `src-tauri/target/**/out/`.
      "src-tauri/target/**",
    ],
  },

  js.configs.recommended,
  ...tseslint.configs.recommended,
  solid,

  {
    languageOptions: {
      ecmaVersion: 2022,
      sourceType: "module",
      globals: { ...globals.browser },
    },
    rules: {
      // Solid components index props/signals directly; the plugin's `typescript`
      // preset requires explicit types on exported functions, which this codebase
      // does not use (everything is inferred from `Component`).
      "@typescript-eslint/explicit-module-boundary-types": "off",
    },
  },

  // Node-side sources: the Vite config, the E2E driver config, the repo scripts.
  {
    files: [
      "*.ts",
      "vite.config.ts",
      "wdio.conf.ts",
      "screenshots.wdio.conf.ts",
      "e2e/**/*.ts",
      "scripts/**/*.{ts,mjs,js}",
    ],
    languageOptions: { globals: { ...globals.node } },
  },

  prettierConfig,
);
